(* Determine if a field is a fundamental field or linear combination of *)
(* fundamental field *)
(* \[CurlyPhi][z]-->True, \[Delta][z]-->True, (\[CurlyPhi]^\[Prime])[z]-->True, *)
(* (\[ExponentialE]^\[CurlyPhi])[z]-->False, k-->False, (1/(z-w))-->False *)
