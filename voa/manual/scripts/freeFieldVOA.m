(* Determine if a simple field is a exponential field *)
(* (\[ExponentialE]^\[CurlyPhi])[z]-->True, (\[ExponentialE]^(\[Lambda] \[CurlyPhi]+\[Mu] \[Delta]))[z]-->True *)
(* \[CurlyPhi][z]-->False, (\[CurlyPhi]^\[Prime])[z]-->False, *)
(* k-->False, (1/(z-w))-->False *)
(* !!! (\[ExponentialE]^(Log[u-v]\[CurlyPhi]))[z] breaks !!! *)
