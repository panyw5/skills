(* compute the OPE coefficient of (z-w)^order between exp1 and exp2 *)
(* e.g. OPEfreeCoefficient[\[Gamma] \[Gamma]^\[Prime],\[Beta]] *)
Clear[OPEfree,OPEFree,OPEfreeCoefficient,OPEFreeCoefficient]

OPEfreeCoefficient[exp1_,exp2_][order_]:=Module[{z,w},
(FullContraction[
exp1//MakeField[#][z]&//Make//NOFree,
exp2//MakeField[#][w]&//Make//NOFree
]//OpToFieldFn//SeriesCoefficient[#,{z,w,order}]&)//FieldFunctionToExpression//OpToFieldName//Expand];
OPEFreeCoefficient=OPEfreeCoefficient;

OPEfree[exp1_,exp2_][z_,w_][order_:0]:=Module[{},
FullContraction[
exp1//MakeField[#][z]&//Make//NOFree,
exp2//MakeField[#][w]&//Make//NOFree
]//OpToFieldFn//Simplify//Series[#,{z,w,order}]&//Normal//FieldFunctionToExpression//MakeField[#][w]&
];
OPEFree=OPEfree;



(* ::Input::Initialization:: *)
Clear[NOCofOp];
(* OPE[o1[z],o2[w]] = SingularOPEs + NOCofOp[o1[z],o2[w]][z,w] + O[z-w] *)
NOCofOp[o1_+o2_,o3_][z_,w_]:=NOCofOp[o1,o3][z,w]+NOCofOp[o2,o3][z,w];
NOCofOp[o1_,o2_+o3_][z_,w_]:=NOCofOp[o1,o2][z,w]+NOCofOp[o1,o3][z,w];

NOCofOp[f_. Op[l1_],g_. Op[l2_]][z_,w_]:=f g FullContraction[Op[l1],Op[l2]]//OpToFieldFn//SeriesCoefficient[#,{z,w,0}]&//FieldFunctionToExpression;

Clear[NOC]

