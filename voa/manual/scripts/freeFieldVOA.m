(* contracted exponential field in fList should be kept *)
result=Op[exponentialFields]Op[uselessFactor]Sum[
Product[
TwoPt[Op[{f[z]}],Op[{possibleContractedWithLabels[[c]][[j]][[1]]}]],
{j,1,Length[possibleContractedWithLabels[[c]]]}
]
Op[RemoveLabels[Complement[fListWithLabels,DeleteCases[possibleContractedWithLabels[[c]],x_/;IsExpField[x[[1]]]==True]]]]Op[{f[z]}]
,{c,1,Length[possibleContractedWithLabels]}
]
]/;IsExpField[f[z]];


