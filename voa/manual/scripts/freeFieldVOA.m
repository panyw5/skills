IsFundField[f_]:=Module[{pattern},
pattern=Table[{
fieldNames[[i]][z_]:>True,
\!\(\*SuperscriptBox[\(fieldNames\[LeftDoubleBracket]i\[RightDoubleBracket]\), 
TagBox[
RowBox[{"(", "n_", ")"}],
Derivative],
MultilineFunction->None]\)[z_]:>True,
\[Lambda]_ fieldNames[[i]][z_]:>True,
\[Lambda]_ \!\(\*SuperscriptBox[\(fieldNames\[LeftDoubleBracket]i\[RightDoubleBracket]\), 
TagBox[
RowBox[{"(", "n_", ")"}],
Derivative],
MultilineFunction->None]\)[z_]:>True,
a_. e1_[z_]+e2_:>(IsFundField[e1[z]]||IsFundField[a])&&IsFundField[e2]
},
{i,Length[fieldNames]}]//Flatten;

(f//Expand)/.pattern//TrueQ
];


