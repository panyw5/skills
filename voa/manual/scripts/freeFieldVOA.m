(* fList\[LeftDoubleBracket]-1\[RightDoubleBracket] eithers participates in NO contraction with the 2nd op (Op2) at all *)
(* and therefore will be stipped off as a bystander in the last line *)
(* (if it's an exponential field, it still will generate multiplicative factors of its 2-pt function 
