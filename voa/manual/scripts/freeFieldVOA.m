ExpressionToFieldFunctionTemp[exp_][z_]:=exp/.{ff_:>ff[z]/;IsFundField[ff[z]]};
(f/.{(E^exp_)[z_]:>E^exp}//ExpressionToFieldFunctionTemp[#][x]&)/.{E^field_:>IsFundField[field]}//TrueQ
];

IsFreeField[f_]:=IsFundField[f]||IsExpField[f];


