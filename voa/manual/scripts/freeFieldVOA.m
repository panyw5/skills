(* -- Initializing *)
(* -- no self-contraction *)
Contraction[Op[{f1_[z_]}],Op[{f2_[z_]}]]:=0;

(* -- Contraction between two fields *)
(* Contractions are between an operator with a fundamental operator *)
(* There is no contraction between two exponential operators; *)
(* they will however contribute a multiplicative factor in FullContraction *)
Contraction[Op[{f1_[z_]}],Op[{f2_[w_]}]]:=(
TwoPt[Op[{f1[z]}],Op[{f2[w]}]]
Op[{}~Join~If[IsExpField[f1[z]],{f1[z]},{}]~Join~If[IsExpField[f2[w]],{f2[w]},{}]]
*If[IsExpField[f1[z]]&&IsExpField[f2[w]],0,1]
)

(* -- Contraction between non-exp field f[z] and Subscript[f, 1][w]Subscript[f, 2][w]... *)
Contraction[Op[{f_[z_]}],Op[fList_]]:=(
Sum[Contraction[Op[{f[z]}],Op[{fList[[ii]]}]]Op[Drop[fList,{ii}]],{ii,1,Length[fList]}]
)/;IsFundField[f[z]]

(* -- Contraction between Subscript[f, 1][z]Subscript[f, 2][z] and a non-exp field f[w]... *)
Contraction[Op[fList_],Op[{f_[w_]}]]:=(
Sum[Contraction[Op[{fList[[ii]]}],Op[{f[w]}]]Op[Drop[fList,{ii}]],{ii,1,Length[fList]}]
)/;IsFundField[f[w]];

(* -- Contraction between an exp field f[z] and Subscript[f, 1][w]Subscript[f, 2][w]... *)
